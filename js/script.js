let standingsCache = null;

function updateStandingsLanguage(language) {
    const t = translations[language];
    if (!t) return;

    const mapping = {
        standingsTitle: "standingsTitle",
        standingsTeam: "standingsTeam",
        standingsPlayed: "standingsPlayed",
        standingsWin: "standingsWin",
        standingsDraw: "standingsDraw",
        standingsLose: "standingsLose",
        standingsGF: "standingsGF",
        standingsGA: "standingsGA",
        standingsGD: "standingsGD",
        standingsPoints: "standingsPoints",
        standingsForm: "standingsForm"
    };

    Object.entries(mapping).forEach(([key, id]) => {
        const element = document.getElementById(id);
        if (element && t[key] !== undefined) {
            element.textContent = t[key];
        }
    });

    const loading = document.getElementById("standingsLoading");
    if (loading && loading.style.display !== "none" && t.standingsLoading) {
        loading.textContent = t.standingsLoading;
    }
}

function renderStandings(standings) {
    const body = document.getElementById("standingsBody");
    const loading = document.getElementById("standingsLoading");

    if (!body || !loading || !Array.isArray(standings)) return;

    loading.style.display = "none";

    body.innerHTML = standings.map(row => {
        const name = row.team?.name || "";
        const logo = row.team?.logo || "";

        const isOrdabasy =
            name.toLowerCase().includes("ordabasy") ||
            name.toLowerCase().includes("ордабасы");

        const goalDiff = Number(row.goalsDiff || 0);
        let diffClass = "";

        if (goalDiff > 0) diffClass = "standings-positive";
        if (goalDiff < 0) diffClass = "standings-negative";

        const formHtml = (row.form || "")
            .slice(-5)
            .split("")
            .map(letter => {
                let className = "form-d";
                if (letter === "W") className = "form-w";
                if (letter === "L") className = "form-l";
                return `<span class="${className}">${letter}</span>`;
            })
            .join("");

        return `
            <tr class="${isOrdabasy ? "ordabasy-standing" : ""}">
                <td class="standings-rank">${row.rank ?? "—"}</td>
                <td>
                    <div class="standings-team">
                        ${logo ? `<img src="${logo}" alt="${name}">` : ""}
                        <strong>${name}</strong>
                    </div>
                </td>
                <td>${row.all?.played ?? 0}</td>
                <td class="standings-win">${row.all?.win ?? 0}</td>
                <td>${row.all?.draw ?? 0}</td>
                <td class="standings-loss">${row.all?.lose ?? 0}</td>
                <td>${row.all?.goals?.for ?? 0}</td>
                <td>${row.all?.goals?.against ?? 0}</td>
                <td class="${diffClass}">${goalDiff > 0 ? "+" : ""}${goalDiff}</td>
                <td class="standings-points">${row.points ?? 0}</td>
                <td>
                    <div class="standings-form">${formHtml}</div>
                </td>
            </tr>
        `;
    }).join("");
}

async function loadLiveStandings() {
    const body = document.getElementById("standingsBody");
    const loading = document.getElementById("standingsLoading");

    if (!body || !loading) return;

    const language = document.documentElement.lang || "kk";
    updateStandingsLanguage(language);

    if (standingsCache) {
        renderStandings(standingsCache);
        return;
    }

    loading.style.display = "block";
    loading.textContent = translations[language]?.standingsLoading || "Loading standings...";

    try {
        const response = await fetch("/.netlify/functions/standings");

        if (!response.ok) {
            throw new Error(`Standings request failed: ${response.status}`);
        }

        const data = await response.json();
        const standings = data.response?.[0]?.league?.standings?.[0];

        if (!Array.isArray(standings) || standings.length === 0) {
            throw new Error("No standings data");
        }

        standingsCache = standings;
        renderStandings(standingsCache);

    } catch (error) {
        console.error("Standings error:", error);
        loading.style.display = "block";
        loading.textContent =
            translations[language]?.standingsError ||
            "Unable to load standings.";
    }
}


