import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { create } from "fontkit";
import subsetFont from "subset-font";

// Same Noto Sans 2.015 as the existing files. Ordinary builds use the committed WOFF2.
const response = await fetch(
  "https://raw.githubusercontent.com/google/fonts/main/ofl/notosans/NotoSans%5Bwdth,wght%5D.ttf",
);
if (!response.ok) throw new Error(`Font source HTTP ${response.status}`);
const source = Buffer.from(await response.arrayBuffer());
if (
  createHash("sha256").update(source).digest("hex") !==
  "bfb7bb691513f12e734dc346c03a03f784912432d7e3fa8e56efcf906fe86b3d"
)
  throw new Error(
    "Upstream font changed; review its version and metrics before updating",
  );
const text =
  Array.from({ length: 95 }, (_, i) => String.fromCodePoint(i + 32)).join("") +
  "ӘәҒғҚқҢңӨөҰұҮүҺһІіАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя «»—–‘’“”·•…№©®€₸×";
const data = await subsetFont(source, text, {
  targetFormat: "woff2",
  variationAxes: { wdth: 100, wght: { min: 400, max: 900 } },
  // Public/admin CSS uses normal weights 400..900 and default shaping only.
  // Keep standard shaping; opt-in small caps, fractions and alternate digits
  // unnecessarily pulled their extra outlines/variations into the preload.
  keepFeatures: [
    "rvrn",
    "ccmp",
    "locl",
    "rlig",
    "mark",
    "mkmk",
    "calt",
    "liga",
    "clig",
    "kern",
  ],
});
const font = create(data);
const old = await Promise.all(
  ["latin", "cyrillic", "cyrillic-ext"].map(async (name) =>
    create(
      await readFile(
        `apps/web/public/fonts/noto-sans-${name}-wght-normal.woff2`,
      ),
    ),
  ),
);
for (const cp of new Set([...text].map((char) => char.codePointAt(0)))) {
  if (!font.hasGlyphForCodePoint(cp))
    throw new Error(`Missing primary glyph U+${cp.toString(16)}`);
  const previous = old.find((item) => item.hasGlyphForCodePoint(cp));
  if (
    previous &&
    (previous.version !== font.version ||
      previous.ascent !== font.ascent ||
      previous.descent !== font.descent ||
      Math.abs(
        previous.glyphForCodePoint(cp).advanceWidth -
          font.glyphForCodePoint(cp).advanceWidth,
      ) > 0.01)
  )
    throw new Error(`Existing font metrics changed for U+${cp.toString(16)}`);
}
// Compare with the previous primary font recipe, including its pinned width.
const original = create(
  await subsetFont(source, text, {
    targetFormat: "sfnt",
    variationAxes: { wdth: 100 },
  }),
);
// fontkit's variation reader expects an SFNT stream (not a WOFF2 wrapper).
const shapedFont = create(
  await subsetFont(data, null, {
    targetFormat: "sfnt",
    keepAllGlyphs: true,
  }),
);
const shapingSamples = [
  text,
  "ӘҒҚҢӨҰҮҺІ Әә Ғғ Ққ Ңң Өө Ұұ Үү Һһ Іі Қазақстан Ордабасы Шымкент",
  "Футбольный клуб История команды 0123456789 2026 №77",
  "FC ORDABASY AV WA To affine office ffi English match news",
];
for (const wght of [400, 500, 600, 700, 800, 900]) {
  const before = original.getVariation({ wdth: 100, wght });
  const after = shapedFont.getVariation({ wght });
  for (const sample of shapingSamples) {
    const a = before.layout(sample),
      b = after.layout(sample);
    if (
      a.glyphs.length !== b.glyphs.length ||
      JSON.stringify(a.positions) !== JSON.stringify(b.positions) ||
      a.glyphs.some(
        (glyph, i) =>
          JSON.stringify(glyph.path.commands) !==
          JSON.stringify(b.glyphs[i].path.commands),
      )
    )
      throw new Error(`Font shaping/outlines changed at weight ${wght}`);
  }
}
const points = font.characterSet.filter((cp) => cp > 0).sort((a, b) => a - b);
const ranges = [];
for (let i = 0; i < points.length; i++) {
  const first = points[i];
  let last = first;
  while (points[i + 1] === last + 1) last = points[++i];
  ranges.push(
    `U+${first.toString(16)}${last > first ? "-" + last.toString(16) : ""}`,
  );
}
await writeFile(
  "apps/web/public/fonts/noto-sans-2.015-primary-wght-normal.woff2",
  data,
);
// Keep the primary in a distinct CSS family. Overlapping ranges in a single
// family made Chrome select the old 100..900 faces instead of this 400..900
// face, downloading all three old files in addition to the unused preload.
const lightFaces = (await readFile("apps/web/styles/fonts.css", "utf8"))
  .replaceAll("'Noto Sans Variable'", "'Noto Sans Primary'")
  .replaceAll("font-weight: 100 900", "font-weight: 100 399");
await writeFile(
  "apps/web/styles/primary-font.css",
  `/* Generated by scripts/build-fonts.mjs; same Noto outlines/shaping. Light weights retain the original subsets. */\n${lightFaces}\n@font-face {\n  font-family: 'Noto Sans Primary';\n  font-style: normal;\n  font-display: swap;\n  font-weight: 400 900;\n  src: url(/fonts/noto-sans-2.015-primary-wght-normal.woff2) format('woff2-variations');\n  unicode-range: ${ranges.join(",")};\n}\n`,
);
console.log(
  `Primary font: ${data.length} bytes; required alphabets and existing metrics verified.`,
);
